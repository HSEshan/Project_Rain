/** Every entry once, for search. */
export const ALL_EMOJI: EmojiEntry[] = EMOJI_CATEGORIES.flatMap((c) => c.emoji);

// Segmenter counts "👍🏽" or "🧑‍💻" as one character, which is what a person
// would count. A browser without it falls back to code points, which only makes
// the large rendering below kick in a little less often. Built once: this runs
// for every message row on every render.
const segmenter =
  typeof Intl !== "undefined" && "Segmenter" in Intl
    ? new Intl.Segmenter(undefined, { granularity: "grapheme" })
    : null;

const graphemes = (text: string): string[] =>
  segmenter
    ? Array.from(segmenter.segment(text), (part) => part.segment)
    : Array.from(text);

// A flag is two regional indicator letters, which are not pictographs themselves
const PICTOGRAPHIC = /\p{Extended_Pictographic}|\p{Regional_Indicator}/u;
// An alternation, not a character class: a joiner inside a class reads as if it
// joined its neighbours, which is what the linter objects to.
const DECORATION = /^(?:\p{Emoji_Modifier}|\p{Emoji_Component}|‍|️|\s)*$/u;

/**
 * A short message that is nothing but emoji, which renders large.
 *
 * Every chat app does this, and for the same reason: a lone 👍 at text size is
 * a speck under a name. Capped at a few, because a wall of large emoji is noise.
 * Digits and `#` are Emoji_Component, so a check on that class alone would
 * enlarge "42"; each grapheme has to contain a pictograph.
 */
export function isJumboEmoji(text: string, max = 6): boolean {
  const trimmed = text.trim();
  if (!trimmed || trimmed.length > 64) return false;
  const parts = graphemes(trimmed).filter((part) => part.trim() !== "");
  if (parts.length === 0 || parts.length > max) return false;
  return parts.every(
    (part) => PICTOGRAPHIC.test(part) && DECORATION.test(part.replace(/\p{Extended_Pictographic}|\p{Regional_Indicator}/gu, ""))
  );
}
